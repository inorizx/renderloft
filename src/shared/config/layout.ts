/**
 * 右侧任务中心（TaskCenter）的布局断点 —— 单一权威位置。
 *
 * 这个数字同时决定三件事，三者必须保持一致，否则会出现「右栏压住内容」这类
 * 无声遮挡（曾真实发生过：浮层判定 1024、让位判定 1280，中间 256px 区间规则打架）：
 *
 *   1. 任务中心是否为浮层 —— `isOverlay`，见 `components/TaskCenter.vue`
 *   2. 主区是否让出 320px —— `margin-right` 媒体查询，见 `components/AppShell.vue`
 *   3. 首次加载是否默认展开 —— 见 `shared/stores/task-center.ts`
 *      （≥ 此宽度 = 常驻侧栏，默认展开；< 此宽度 = 浮层，默认收起，避免一进页面就盖住内容）
 *
 * ⚠️ CSS 媒体查询读不到 JS 常量：`AppShell.vue` 里写的是字面量 `1200px`，
 * 该处有注释互相指认。改这里时必须同步改那里。
 *
 * ⚠️ **为什么是 1200，而不是原来那个 1280**：桌面外壳的默认窗口就是 **1200×800**
 * （`desktop/tauri.conf.json`）。阈值写 1280 时，**默认窗口正好落在浮层档**——
 * 于是"第一次打开这个应用"看到的是：右栏默认收起、打开它就整片压暗、主区不让位。
 * 而任务中心是这个产品的主画面之一（任务进度就在那儿），不该在默认尺寸下被藏起来。
 * **默认窗口多宽，常驻阈值就不该高于它。**
 *
 * 1200 时三栏的账：导航 240（`w-60`）+ 内容 640 + 右栏 320。内容 640 比浮层态下
 * 实际能用的 ~603 还宽一点，所以这个改动不是拿内容换右栏。
 */
export const TASKCENTER_OVERLAY_MAX_WIDTH = 1200
